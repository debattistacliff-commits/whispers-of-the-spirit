// Builds ../console.offline.css: Tailwind utilities used by the console, the console fonts and the
// Font Awesome icons it uses, all inlined so the page needs no internet connection.
// Usage: npm install && npm run build   (run again after changing console.html, console-live.js or WebConsole.cs)
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const here = __dirname, out = path.join(here, '..', 'console.offline.css');
const tmp = path.join(here, 'tailwind.out.css');
execFileSync(process.execPath, [require.resolve('tailwindcss/lib/cli.js'), '-c', path.join(here, 'tailwind.config.js'), '-i', path.join(here, 'input.css'), '-o', tmp, '--minify'], { cwd: here, stdio: 'inherit' });
const tailwind = fs.readFileSync(tmp, 'utf8'); fs.unlinkSync(tmp);

const font = (pkg, file, family, weight) => {
  const data = fs.readFileSync(path.join(path.dirname(require.resolve(pkg + '/package.json')), 'files', file)).toString('base64');
  return `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;src:url(data:font/woff2;base64,${data}) format("woff2")}`;
};
const fonts = [
  font('@fontsource/share-tech-mono', 'share-tech-mono-latin-400-normal.woff2', 'Share Tech Mono', 400),
  font('@fontsource/jetbrains-mono', 'jetbrains-mono-latin-400-normal.woff2', 'JetBrains Mono', 400),
  font('@fontsource/jetbrains-mono', 'jetbrains-mono-latin-700-normal.woff2', 'JetBrains Mono', 700),
  font('@fontsource/space-grotesk', 'space-grotesk-latin-400-normal.woff2', 'Space Grotesk', 400),
  font('@fontsource/space-grotesk', 'space-grotesk-latin-700-normal.woff2', 'Space Grotesk', 700),
].join('\n');

// Icons: every fa-* name used in the console, drawn as a CSS mask so it takes the text colour.
const sources = ['../console.html', '../console-live.js', '../review-deck.js', '../../WebConsole.cs'].map(f => fs.readFileSync(path.join(here, f), 'utf8')).join('\n');
const names = [...new Set([...sources.matchAll(/\bfa-([a-z0-9-]+)/g)].map(m => m[1]))].filter(n => n !== 'solid');
const svgDir = path.join(path.dirname(require.resolve('@fortawesome/fontawesome-free/package.json')), 'svgs', 'solid');
const icons = names.map(n => {
  const file = path.join(svgDir, n + '.svg');
  if (!fs.existsSync(file)) throw new Error('Unknown Font Awesome icon: ' + n);
  const svg = fs.readFileSync(file, 'utf8').replace(/<!--.*?-->/gs, '').trim();
  return `.fa-${n}{--fa-icon:url("data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}")}`;
});
const iconBase = '.fa-solid{display:inline-block;width:1.1em;height:1em;vertical-align:-0.125em;background-color:currentColor;-webkit-mask:var(--fa-icon) no-repeat center/contain;mask:var(--fa-icon) no-repeat center/contain}';

fs.writeFileSync(out, `/* Generated by tools/build.js — do not edit by hand. Licences: see THIRD-PARTY.md */\n${fonts}\n${iconBase}\n${icons.join('\n')}\n${tailwind}`);
console.log('Wrote', out, (fs.statSync(out).size / 1024).toFixed(0) + ' KB', 'icons:', names.join(', '));
